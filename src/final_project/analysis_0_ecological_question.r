# The global idea is to see the habitat of Amanita muscaria (a mycorhizal fungi)
# Several questions are asked for this project : 

    # What is the tree preference (between 7 different tree species) of A. muscaria ?
    # How is the niche of the two best preferred tree and particularly A. muscaria represented in France with a random forest analysis ? 
    # What is the most important variable explaining the presence of A. muscaria and it's two best preferred tree ? 
    # How the different environmental variables contribute to the presence of A. muscaria ?